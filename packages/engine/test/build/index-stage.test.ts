import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { runIndexStage } from "../../src/build/index-stage.js";
import { getPageFromLlmsTxt } from "../../src/mcp/get-page.js";
import type { BuildPageResult } from "../../src/pages/index.js";

async function writeFakePage(pagesDir: string, id: string, title: string, publishable = true): Promise<BuildPageResult> {
  const pageDir = path.join(pagesDir, id);
  await mkdir(pageDir, { recursive: true });
  const indexFile = path.join(pageDir, "index.md");
  const plainFile = path.join(pageDir, "index.plain.md");
  await writeFile(
    indexFile,
    `---\ntitle: ${title}\npassed: ${publishable}\n---\n\n# ${title}\n\nSome body text about ${id}.\n`,
  );
  await writeFile(plainFile, `${title}\n\nSome body text about ${id}.\n`);
  return {
    id,
    outDir: pageDir,
    indexFile,
    plainFile,
    screenshotsDir: path.join(pageDir, "screenshots"),
    screenshots: [],
    passed: publishable,
    publishable,
    problems: [],
    suggestions: [],
  };
}

describe("runIndexStage", () => {
  let dir: string;
  let pagesDir: string;
  let outDir: string;

  beforeEach(async () => {
    dir = await mkdtemp(path.join(os.tmpdir(), "aida-index-"));
    outDir = path.join(dir, "out");
    pagesDir = path.join(outDir, "pages");
    await mkdir(pagesDir, { recursive: true });
  });
  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it("writes search-index.json and llms.txt under outDir when there's no help app", async () => {
    const pages = [await writeFakePage(pagesDir, "add-competitor", "Add a competitor")];
    const result = runIndexStage({ pagesDir, outDir, pages });

    expect(result.copiedToHelpApp).toBe(false);
    expect(existsSync(result.searchIndexFile)).toBe(true);
    expect(existsSync(result.llmsTxtFile)).toBe(true);
    expect(result.pageCount).toBe(1);

    const llms = await readFile(result.llmsTxtFile, "utf8");
    expect(llms).toContain("Add a competitor");
  });

  it("skips non-publishable pages in llms.txt and never stages them into content/docs at all (bug: could leak personal data/secrets from a failed run)", async () => {
    const pages = [
      await writeFakePage(pagesDir, "good", "Good page", true),
      await writeFakePage(pagesDir, "bad", "Bad page", false),
    ];
    const result = runIndexStage({ pagesDir, outDir, pages });
    const llms = await readFile(result.llmsTxtFile, "utf8");
    expect(llms).toContain("Good page");
    expect(llms).not.toContain("Bad page");
    expect(existsSync(path.join(result.contentDir, "bad"))).toBe(false);
  });

  it("removes a previously-published page's staged copy once it stops being publishable", async () => {
    const helpApp = path.join(dir, "help");
    const good = await writeFakePage(pagesDir, "flaky", "Flaky page", true);
    runIndexStage({ pagesDir, outDir, helpApp, pages: [good] });
    const destDir = path.join(helpApp, "content", "docs", "how-do-i", "flaky");
    expect(existsSync(destDir)).toBe(true);

    const nowFailing = await writeFakePage(pagesDir, "flaky", "Flaky page", false);
    runIndexStage({ pagesDir, outDir, helpApp, pages: [nowFailing] });
    expect(existsSync(destDir)).toBe(false);
  });

  it("writes a generated-content header into each page staged into content/docs", async () => {
    const helpApp = path.join(dir, "help");
    const pages = [await writeFakePage(pagesDir, "add-competitor", "Add a competitor")];
    runIndexStage({ pagesDir, outDir, helpApp, pages });
    const staged = await readFile(path.join(helpApp, "content", "docs", "how-do-i", "add-competitor", "index.md"), "utf8");
    expect(staged).toContain("Generated by aida");
    expect(staged).toContain("pages/add-competitor/index.mdx");
  });

  it("prunes the staged page of a walkthrough that no longer exists on disk", async () => {
    const helpApp = path.join(dir, "help");
    const gone = await writeFakePage(pagesDir, "deleted-flow", "Deleted flow");
    runIndexStage({ pagesDir, outDir, helpApp, pages: [gone], walkthroughIds: ["deleted-flow"] });
    const destDir = path.join(helpApp, "content", "docs", "how-do-i", "deleted-flow");
    expect(existsSync(destDir)).toBe(true);

    // Next run: "deleted-flow"'s walkthrough file is gone, and this run didn't rebuild it.
    runIndexStage({ pagesDir, outDir, helpApp, pages: [], walkthroughIds: [] });
    expect(existsSync(destDir)).toBe(false);
  });

  it("does not prune anything when walkthroughIds isn't given (back-compat for callers that don't track the full set)", async () => {
    const helpApp = path.join(dir, "help");
    const page = await writeFakePage(pagesDir, "add-competitor", "Add a competitor");
    runIndexStage({ pagesDir, outDir, helpApp, pages: [page] });
    runIndexStage({ pagesDir, outDir, helpApp, pages: [] });
    expect(existsSync(path.join(helpApp, "content", "docs", "how-do-i", "add-competitor"))).toBe(true);
  });

  it("builds llms.txt from every published page on disk, not just the ones this call rebuilt (aida build <one-walkthrough> must not drop the rest)", async () => {
    const helpApp = path.join(dir, "help");
    const a = await writeFakePage(pagesDir, "walkthrough-a", "Walkthrough A");
    const b = await writeFakePage(pagesDir, "walkthrough-b", "Walkthrough B");
    runIndexStage({ pagesDir, outDir, helpApp, pages: [a, b], walkthroughIds: ["walkthrough-a", "walkthrough-b"] });

    // A later call only rebuilds "walkthrough-a" (e.g. `aida build walkthrough-a`).
    const result = runIndexStage({ pagesDir, outDir, helpApp, pages: [a], walkthroughIds: ["walkthrough-a", "walkthrough-b"] });
    const llms = await readFile(result.llmsTxtFile, "utf8");
    expect(llms).toContain("Walkthrough A");
    expect(llms).toContain("Walkthrough B");
  });

  it("copies pages into <helpApp>/content/docs and writes search-index.json/llms.txt under <helpApp>/public", async () => {
    const helpApp = path.join(dir, "help");
    const pages = [await writeFakePage(pagesDir, "add-competitor", "Add a competitor")];
    const result = runIndexStage({ pagesDir, outDir, helpApp, pages });

    expect(result.copiedToHelpApp).toBe(true);
    expect(existsSync(path.join(helpApp, "content", "docs", "how-do-i", "add-competitor", "index.md"))).toBe(true);
    expect(result.searchIndexFile).toBe(path.join(helpApp, "public", "search-index.json"));
    expect(existsSync(result.searchIndexFile)).toBe(true);
    expect(existsSync(path.join(helpApp, "public", "llms.txt"))).toBe(true);
  });

  it("does not double-count a page's index.plain.md as a second page", async () => {
    const pages = [await writeFakePage(pagesDir, "add-competitor", "Add a competitor")];
    const result = runIndexStage({ pagesDir, outDir, pages });
    expect(result.pageCount).toBe(1);
  });

  it("llms.txt stays parseable by get_page when index.plain.md still carries its page's YAML frontmatter and a body horizontal rule (regression: both are `---`-delimited, and used to collide with the old section delimiter so get_page returned empty for every page)", async () => {
    const id = "add-contact";
    const pageDir = path.join(pagesDir, id);
    await mkdir(pageDir, { recursive: true });
    const indexFile = path.join(pageDir, "index.md");
    // `pages/build.ts` writes index.plain.md as `stripMarkers(text)` of the *whole* page,
    // frontmatter block included — this mirrors that real shape, not a synthetic plain-text file.
    const plainText = [
      "---",
      'title: "Add a new contact"',
      'walkthrough: "add-contact"',
      "passed: true",
      "---",
      "",
      "# Add a new contact",
      "",
      "Click Add contact.",
      "",
      "---",
      "",
      "*Steps verified against the real app.*",
      "",
    ].join("\n");
    await writeFile(path.join(pageDir, "index.plain.md"), plainText);
    await writeFile(indexFile, `---\ntitle: "Add a new contact"\npassed: true\n---\n\n# Add a new contact\n`);
    const page: BuildPageResult = {
      id,
      outDir: pageDir,
      indexFile,
      plainFile: path.join(pageDir, "index.plain.md"),
      screenshotsDir: path.join(pageDir, "screenshots"),
      screenshots: [],
      passed: true,
      publishable: true,
      problems: [],
      suggestions: [],
    };

    const result = runIndexStage({ pagesDir, outDir, pages: [page] });
    const llms = await readFile(result.llmsTxtFile, "utf8");

    // The frontmatter and the body's own `---` horizontal rule must not have been treated as
    // the llms.txt section delimiter, nor leaked into the page's extracted content.
    expect(llms).not.toContain("title:");
    const content = getPageFromLlmsTxt(llms, id);
    expect(content).toContain("Click Add contact.");
    expect(content).toContain("Steps verified against the real app.");
    expect(content).not.toContain("title:");
  });

  // Regression (review finding index-stage.ts:152): a page that's unpublishable this run (e.g.
  // because its QA scan failed, which pipeline.ts now reflects by overriding `publishable` to
  // false before calling here — see finalPublishable()) must have its screenshots and procedures
  // entry removed too, not just content/docs.
  it("removes a walkthrough's public/screenshots/<id> and procedures.json entry once it stops being publishable", async () => {
    const helpApp = path.join(dir, "help");
    const wf = {
      walkthrough: "flaky",
      title: "Flaky walkthrough",
      start: {},
      steps: [],
    } as unknown as import("../../src/walkthrough/index.js").Walkthrough;

    const good = await writeFakePage(pagesDir, "flaky", "Flaky walkthrough", true);
    const captureDir = path.join(dir, "capture");
    await mkdir(path.join(captureDir, "frames"), { recursive: true });
    await writeFile(path.join(captureDir, "manifest.json"), JSON.stringify({ steps: [] }));
    await writeFile(path.join(captureDir, "validation.json"), JSON.stringify({ ok: true, steps: [] }));

    // First run: publishable, procedures.json + a screenshots dir (seeded by hand — the real
    // screenshot-copy path is exercised in procedures/build.test.ts) both exist afterwards.
    const r1 = runIndexStage({
      pagesDir,
      outDir,
      helpApp,
      pages: [good],
      procedureSources: [{ walkthrough: wf, captureDir }],
    });
    expect(r1.procedures?.map((p) => p.id)).toEqual(["flaky"]);
    const screenshotsDir = path.join(helpApp, "public", "screenshots", "flaky");
    await mkdir(screenshotsDir, { recursive: true });
    await writeFile(path.join(screenshotsDir, "step-01.png"), "fake");

    // Second run: this run attempted "flaky" again but it's no longer publishable (QA failed) —
    // pipeline.ts passes it through with `publishable: false` rather than omitting it.
    const failing = await writeFakePage(pagesDir, "flaky", "Flaky walkthrough", false);
    const r2 = runIndexStage({
      pagesDir,
      outDir,
      helpApp,
      pages: [failing],
      procedureSources: [{ walkthrough: wf, captureDir }],
    });
    expect(r2.procedures).toEqual([]);
    expect(existsSync(screenshotsDir)).toBe(false);
    expect(existsSync(path.join(helpApp, "content", "docs", "how-do-i", "flaky"))).toBe(false);
  });

  it("keeps an existing procedures.json entry for a walkthrough this run didn't touch at all", async () => {
    const helpApp = path.join(dir, "help");
    const proceduresFile = path.join(helpApp, "public", "procedures.json");
    await mkdir(path.dirname(proceduresFile), { recursive: true });
    await writeFile(proceduresFile, JSON.stringify([{ id: "untouched", title: "Untouched", start: {}, steps: [] }]));

    const page = await writeFakePage(pagesDir, "add-competitor", "Add a competitor", true);
    const result = runIndexStage({ pagesDir, outDir, helpApp, pages: [page] });
    expect(result.procedures).toBeUndefined(); // procedureSources omitted — this call never touches procedures.json

    const onDisk = JSON.parse(await readFile(proceduresFile, "utf8"));
    expect(onDisk.map((p: { id: string }) => p.id)).toEqual(["untouched"]);
  });

  it("re-copying a page into the help app replaces stale files from a previous build", async () => {
    const helpApp = path.join(dir, "help");
    await writeFakePage(pagesDir, "add-competitor", "Add a competitor");
    const destDir = path.join(helpApp, "content", "docs", "how-do-i", "add-competitor");
    await mkdir(path.join(destDir, "screenshots"), { recursive: true });
    await writeFile(path.join(destDir, "screenshots", "step-09.png"), "stale step");
    await writeFile(path.join(destDir, "index.mdx"), '---\ntitle: "Old"\nwalkthrough: "add-competitor"\n---\n');

    const pages = [await writeFakePage(pagesDir, "add-competitor", "Add a competitor v2")];
    runIndexStage({ pagesDir, outDir, helpApp, pages });

    expect(existsSync(path.join(destDir, "screenshots", "step-09.png"))).toBe(false);
    expect(existsSync(path.join(destDir, "index.mdx"))).toBe(false);
    expect(existsSync(path.join(destDir, "index.md"))).toBe(true);
  });
});
