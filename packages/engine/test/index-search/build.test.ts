import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { buildSearchIndex } from "../../src/index-search/build.js";

const createdDirs: string[] = [];

function tmpDir(): string {
  const dir = mkdtempSync(join(tmpdir(), "aida-search-index-test-"));
  createdDirs.push(dir);
  return dir;
}

afterEach(() => {
  while (createdDirs.length > 0) {
    rmSync(createdDirs.pop()!, { recursive: true, force: true });
  }
});

describe("buildSearchIndex", () => {
  it("builds one entry per lead paragraph/heading, with urls derived from the file tree", () => {
    const dir = tmpDir();
    mkdirSync(join(dir, "how-do-i", "add-competitor"), { recursive: true });
    writeFileSync(
      join(dir, "how-do-i", "add-competitor", "index.md"),
      [
        "---",
        'title: "Add a competitor"',
        "passed: true",
        "---",
        "",
        "Here's how to add a new competitor to a show.",
        "",
        "## Open the competitors page",
        "",
        'Select **Competitors** from the sidebar, then <!-- aida:begin step-1 -->click Add<!-- aida:end step-1 -->.',
        "",
        "## Fill in their details",
        "",
        "Type their first and last name.",
      ].join("\n"),
    );

    const result = buildSearchIndex(dir);

    expect(result.pageCount).toBe(1);
    expect(result.entries.length).toBe(3);
    expect(result.entries[0]).toMatchObject({ url: "/how-do-i/add-competitor", title: "Add a competitor" });
    expect(result.entries[0].heading).toBeUndefined();
    expect(result.entries[0].text).toContain("add a new competitor");
    expect(result.entries.map((e) => e.heading)).toEqual([undefined, "Open the competitors page", "Fill in their details"]);
    // aida marker comments never leak into indexed text.
    expect(result.entries.some((e) => e.text.includes("aida:"))).toBe(false);
  });

  it("strips MDX-comment-style aida markers ({/* aida:begin k */}), not just the HTML-comment form (bug: MDX markers leaked into search snippets)", () => {
    const dir = tmpDir();
    mkdirSync(join(dir, "add-competitor"), { recursive: true });
    writeFileSync(
      join(dir, "add-competitor", "index.mdx"),
      [
        "---",
        'title: "Add a competitor"',
        "passed: true",
        "---",
        "",
        "Here's how to add a new competitor to a show.",
        "",
        "## Open the competitors page",
        "",
        "Select Competitors from the sidebar, then {/* aida:begin step-1 */}click Add{/* aida:end step-1 */}.",
      ].join("\n"),
    );

    const result = buildSearchIndex(dir);

    expect(result.entries.some((e) => e.text.includes("aida:"))).toBe(false);
    expect(result.entries.some((e) => e.text.includes("click Add"))).toBe(true);
  });

  it("skips pages marked passed: false", () => {
    const dir = tmpDir();
    writeFileSync(join(dir, "broken.md"), '---\ntitle: "Broken"\npassed: false\n---\n\nShould not appear.\n');

    const result = buildSearchIndex(dir);
    expect(result.pageCount).toBe(0);
    expect(result.entries).toEqual([]);
  });

  it("maps content/docs/index.mdx to the root url and writes outFile when given", () => {
    const dir = tmpDir();
    writeFileSync(join(dir, "index.mdx"), '---\ntitle: "Welcome"\n---\n\nStart here.\n');
    const outFile = join(tmpDir(), "search-index.json");

    const result = buildSearchIndex(dir, outFile);

    expect(result.entries[0].url).toBe("/");
    expect(result.outFile).toBe(outFile);
    const written = JSON.parse(readFileSync(outFile, "utf8"));
    expect(written).toEqual(result.entries);
  });

  it("returns an empty result for a missing content directory", () => {
    const result = buildSearchIndex(join(tmpdir(), "does-not-exist-" + Date.now()));
    expect(result).toEqual({ entries: [], pageCount: 0 });
  });
  it("gives heading entries the rendered heading's #anchor (github-slugger style, repeats numbered) and carries the page's section", () => {
    const dir = tmpDir();
    mkdirSync(join(dir, "how-do-i", "payments", "record-a-payment"), { recursive: true });
    writeFileSync(
      join(dir, "how-do-i", "payments", "record-a-payment", "index.mdx"),
      [
        "---",
        'title: "Record a payment"',
        'section: "How do I… / Payments"',
        "passed: true",
        "---",
        "{/* Generated by aida — edit in the Studio or pages/record-a-payment/index.mdx */}",
        "",
        "{/* aida:begin header */}",
        "# Record a payment",
        "",
        "Record an entry fee \\{paid\\} at the office.",
        "{/* aida:end header */}",
        "",
        "## Before you start",
        "",
        "- Sign in as **office staff**.",
        "",
        "### Part 1: Record the payment",
        "",
        "#### 1. Open Payments",
        "",
        "Click **Payments**. <Callout type=\"info\">Payments is in the left menu.</Callout>",
        "",
        "![Open Payments](screenshots/step-01.png)",
        "",
        "## Before you start",
        "",
        "Again.",
      ].join("\n"),
    );

    const { entries } = buildSearchIndex(dir);
    const page = "/how-do-i/payments/record-a-payment";
    expect(entries.map((e) => e.url)).toEqual([
      page,
      `${page}#before-you-start`,
      `${page}#part-1-record-the-payment`,
      `${page}#before-you-start-1`,
    ]);
    expect(entries.every((e) => e.section === "How do I… / Payments")).toBe(true);
    const all = entries.map((e) => e.text).join(" ");
    expect(all).not.toMatch(/Generated by aida|aida:|\{\/|\*\/|<Callout|screenshots\/|!\[/);
    expect(entries[0].text).toBe("Record an entry fee {paid} at the office.");
    expect(entries[1].text).toBe("Sign in as office staff.");
    expect(entries[2].text).toContain("1. Open Payments Click Payments. Payments is in the left menu.");
  });

  it("skips template placeholders and index.plain.md files, and indexes a body-less section page by title and description", () => {
    const dir = tmpDir();
    mkdirSync(join(dir, "getting-started"), { recursive: true });
    writeFileSync(join(dir, "getting-started", "index.mdx"), '---\ntitle: "Getting started"\nplaceholder: true\n---\n');
    mkdirSync(join(dir, "how-do-i", "payments"), { recursive: true });
    writeFileSync(
      join(dir, "how-do-i", "payments", "index.mdx"),
      '---\ntitle: "Payments"\ndescription: "Step-by-step guides for payments."\nkind: section\ngenerated: true\n---\n',
    );
    mkdirSync(join(dir, "whats-new"), { recursive: true });
    writeFileSync(join(dir, "whats-new", "index.plain.md"), "# What's new\n\nThings.\n");

    const { entries, pageCount } = buildSearchIndex(dir);
    expect(pageCount).toBe(1);
    expect(entries).toEqual([{ url: "/how-do-i/payments", title: "Payments", text: "Step-by-step guides for payments." }]);
  });
});
