// The help library's folder structure under `<helpApp>/content/docs` (docs/scope.md "Help site";
// Contract 3 in the help-site polish brief): where each walkthrough page is staged, which section
// folders exist, their index pages and `meta.json` sidebar order, the root order, and the home
// page. Everything here is careful about ownership: the engine only rewrites an index page that
// is missing, a template placeholder (`placeholder: true`) or its own (`generated: true`), only
// rewrites a `meta.json` that is missing, its own (`"generated": true`) or the untouched template
// default, never deletes a top-level category folder, and never touches a human-written page.
import {
  existsSync,
  linkSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  rmdirSync,
  statSync,
  unlinkSync,
  copyFileSync,
  utimesSync,
  writeFileSync,
} from "node:fs";
import { join, relative, resolve, sep } from "node:path";
import { frontmatterBlock, readFrontmatter } from "../pages/frontmatter.js";
import { LIBRARY_CATEGORIES, type LibraryPlacement } from "../walkthrough/index.js";

const PAGE_FILES = ["index.mdx", "index.md"];
const CATEGORY_SLUGS = new Set(LIBRARY_CATEGORIES.map((c) => c.slug));
/** Root sidebar order (Contract 3). */
export const ROOT_ORDER = ["index", ...LIBRARY_CATEGORIES.map((c) => c.slug)];

// Text the original (pre-`placeholder: true`) help-app template shipped in its placeholder pages —
// an already-scaffolded help app still has these, so they count as placeholders too.
const LEGACY_PLACEHOLDER_TEXT = [
  "This is a prescaffolded aida help app.",
  "No walkthroughs have generated a page here yet.",
];

/** A walkthrough page staged somewhere in the content tree. */
export interface StagedPage {
  id: string;
  /** Absolute page folder. */
  dir: string;
  /** Folder relative to the content dir, `/`-separated, e.g. "how-do-i/payments/record-a-payment". */
  rel: string;
  /** Absolute path of the page file (`index.mdx` or `index.md`). */
  file: string;
  title: string;
}

function toPosix(p: string): string {
  return p.split(sep).join("/");
}

function pageFileIn(dir: string): string | undefined {
  for (const name of PAGE_FILES) {
    const file = join(dir, name);
    if (existsSync(file)) return file;
  }
  return undefined;
}

/** The walkthrough id a staged page belongs to: its frontmatter `walkthrough:`, or (for a page
 * staged without one) the id in the generated header the index stage writes into every copy. */
function walkthroughIdOf(raw: string): string | undefined {
  const fm = readFrontmatter(raw);
  if (typeof fm.walkthrough === "string" && fm.walkthrough) return fm.walkthrough;
  const header = raw.match(/Generated by aida — edit in the Studio or pages\/([a-z0-9][a-z0-9-]*)\/index\.mdx/);
  return header?.[1];
}

/** Every walkthrough page in `contentDir`, found by what the page says it is (its `walkthrough:`
 * frontmatter), not by folder name — so a page is found wherever an earlier build put it. */
export function findStagedPages(contentDir: string): StagedPage[] {
  const out: StagedPage[] = [];
  if (!existsSync(contentDir)) return out;
  const walk = (dir: string): void => {
    if (dir !== contentDir) {
      const file = pageFileIn(dir);
      if (file) {
        const raw = readFileSync(file, "utf8");
        const id = walkthroughIdOf(raw);
        if (id) {
          const fm = readFrontmatter(raw);
          out.push({ id, dir, rel: toPosix(relative(contentDir, dir)), file, title: typeof fm.title === "string" ? fm.title : id });
        }
      }
    }
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory() && entry.name !== "screenshots" && entry.name !== "node_modules" && !entry.name.startsWith(".")) {
        walk(join(dir, entry.name));
      }
    }
  };
  walk(contentDir);
  return out.sort((a, b) => a.rel.localeCompare(b.rel));
}

/** Removes a staged walkthrough page's own files (page, sidecar, screenshots) — never anything
 * else that happens to share its folder — then the folder itself if that left it empty. */
export function removeStagedPage(dir: string): void {
  for (const name of PAGE_FILES) {
    rmSync(join(dir, name), { force: true });
    rmSync(join(dir, `${name}.aida.json`), { force: true });
  }
  rmSync(join(dir, "index.plain.md"), { force: true });
  rmSync(join(dir, "screenshots"), { recursive: true, force: true });
  removeIfEmpty(dir);
}

function removeIfEmpty(dir: string): void {
  try {
    if (existsSync(dir) && readdirSync(dir).length === 0) rmdirSync(dir);
  } catch {
    // Not empty after all, or already gone — either way nothing to do.
  }
}

/** Links `src` to `dest` (a hardlink, so a large video isn't stored twice on disk), falling back
 * to a copy across filesystems. Skips when `dest` is already the same file or an equal copy. */
export function linkOrCopy(src: string, dest: string): void {
  if (resolve(src) === resolve(dest)) return;
  const s = statSync(src);
  if (existsSync(dest)) {
    const d = statSync(dest);
    if (d.ino === s.ino && d.dev === s.dev) return;
    if (d.size === s.size && d.mtimeMs >= s.mtimeMs) return;
    unlinkSync(dest);
  }
  try {
    linkSync(src, dest);
  } catch {
    copyFileSync(src, dest);
    utimesSync(dest, s.atime, s.mtime);
  }
}

function isReplaceableIndex(file: string): boolean {
  if (!existsSync(file)) return true;
  const raw = readFileSync(file, "utf8");
  const fm = readFrontmatter(raw);
  if (fm.placeholder === true || fm.generated === true) return true;
  return LEGACY_PLACEHOLDER_TEXT.some((t) => raw.includes(t));
}

function indexInfo(dir: string): { title?: string; generated: boolean; placeholder: boolean; kind?: string } {
  const file = pageFileIn(dir);
  if (!file) return { generated: false, placeholder: false };
  const fm = readFrontmatter(readFileSync(file, "utf8"));
  return {
    title: typeof fm.title === "string" ? fm.title : undefined,
    generated: fm.generated === true,
    placeholder: fm.placeholder === true,
    kind: typeof fm.kind === "string" ? fm.kind : undefined,
  };
}

function writeIfChanged(file: string, content: string): void {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return;
  writeFileSync(file, content, "utf8");
}

function lowerFirstWord(title: string): string {
  const [first, ...rest] = title.split(" ");
  // Keep acronyms ("FAQ", "GST") and names in capitals as they are.
  const lowered = first.length > 1 && first === first.toUpperCase() ? first : first.charAt(0).toLowerCase() + first.slice(1);
  return [lowered, ...rest].join(" ");
}

function sectionIndexText(title: string, description: string, extra: Record<string, boolean> = {}): string {
  return `${frontmatterBlock({ title, description, kind: "section", generated: true, ...extra })}\n`;
}

function readJsonObject(file: string): Record<string, unknown> | undefined {
  if (!existsSync(file)) return undefined;
  try {
    const parsed = JSON.parse(readFileSync(file, "utf8")) as unknown;
    return parsed && typeof parsed === "object" && !Array.isArray(parsed) ? (parsed as Record<string, unknown>) : undefined;
  } catch {
    return undefined;
  }
}

/** True for a `meta.json` the engine may rewrite: missing, marked `"generated": true`, or one of
 * the help-app template's untouched defaults (just a `title`, or the older `pages: ["index"]`,
 * which hid every other page and made Fumadocs drop the folder's own index). */
function isManagedMeta(meta: Record<string, unknown> | undefined): boolean {
  if (!meta) return true;
  if (meta.generated === true) return true;
  if (!Object.keys(meta).every((k) => k === "title" || k === "pages")) return false;
  const pages = meta.pages;
  return pages === undefined || (Array.isArray(pages) && pages.length === 1 && pages[0] === "index");
}

function writeMeta(dir: string, title: string, children: string[]): void {
  const file = join(dir, "meta.json");
  const existing = readJsonObject(file);
  if (existsSync(file) && !existing) return; // unreadable — someone's mid-edit; leave it
  if (isManagedMeta(existing)) {
    // Never list "index": Fumadocs then treats it as a child page instead of the folder's own page.
    const meta = { title, pages: [...children.filter((c) => c !== "index"), "..."], generated: true };
    writeIfChanged(file, `${JSON.stringify(meta, null, 2)}\n`);
    return;
  }
  // A person's own meta.json: keep it, but make sure an explicit `pages` list without "..."
  // doesn't hide a page the engine just placed here.
  const pages = existing?.pages;
  if (!Array.isArray(pages) || pages.includes("...")) return;
  const missing = children.filter((c) => !pages.includes(c));
  if (missing.length === 0) return;
  writeIfChanged(file, `${JSON.stringify({ ...existing, pages: [...pages, ...missing] }, null, 2)}\n`);
}

export interface LibraryStructureOptions {
  contentDir: string;
  /** Placement of every walkthrough the caller knows about, keyed by id. */
  placements: Map<string, LibraryPlacement>;
  /** Product name for the home page title ("<Product> help"). */
  product?: string;
}

/**
 * Writes the library's structure around the staged walkthrough pages: removes section folders
 * the engine generated that are now empty, writes each in-use category/section `index.mdx` and
 * `meta.json`, the root `meta.json` order, and the home page.
 */
export function writeLibraryStructure(opts: LibraryStructureOptions): void {
  const { contentDir } = opts;
  mkdirSync(contentDir, { recursive: true });
  const pages = findStagedPages(contentDir);
  const pageRels = new Set(pages.map((p) => p.rel));

  // Folders holding at least one walkthrough page, with the title the walkthrough's section gives
  // them (when known).
  const inUse = new Map<string, string | undefined>();
  for (const page of pages) {
    const parts = page.rel.split("/");
    const placement = opts.placements.get(page.id);
    const known = placement && placement.dir === page.rel ? [placement.category.title, ...placement.groups.map((g) => g.title)] : [];
    for (let depth = 1; depth < parts.length; depth++) {
      const rel = parts.slice(0, depth).join("/");
      const title = known[depth - 1];
      if (!inUse.has(rel) || (title && !inUse.get(rel))) inUse.set(rel, title);
    }
  }

  removeEmptyGeneratedSections(contentDir, contentDir, inUse);

  const titleOf = (rel: string): string => {
    const known = inUse.get(rel);
    if (known) return known;
    const category = LIBRARY_CATEGORIES.find((c) => c.slug === rel);
    if (category) return category.title;
    const fromIndex = indexInfo(join(contentDir, rel)).title;
    if (fromIndex) return fromIndex;
    const name = rel.split("/").pop() ?? rel;
    return name.charAt(0).toUpperCase() + name.slice(1).replace(/-/g, " ");
  };

  const childrenOf = (rel: string): string[] => {
    const dir = join(contentDir, rel);
    const sections: { slug: string; title: string }[] = [];
    const leaves: { slug: string; title: string }[] = [];
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const childRel = `${rel}/${entry.name}`;
      if (pageRels.has(childRel)) {
        leaves.push({ slug: entry.name, title: pages.find((p) => p.rel === childRel)?.title ?? entry.name });
      } else if (inUse.has(childRel)) {
        sections.push({ slug: entry.name, title: titleOf(childRel) });
      }
    }
    const byTitle = (a: { title: string }, b: { title: string }) => a.title.localeCompare(b.title);
    return [...sections.sort(byTitle), ...leaves.sort(byTitle)].map((c) => c.slug);
  };

  // Top-level categories: never deleted. One with walkthrough pages gets a section index (unless
  // a person wrote their own); one the engine filled before that has none left goes back to a
  // placeholder, which the site hides.
  for (const category of LIBRARY_CATEGORIES) {
    const dir = join(contentDir, category.slug);
    const used = inUse.has(category.slug);
    if (!used && !existsSync(dir)) continue;
    mkdirSync(dir, { recursive: true });
    // What's new is written by `aida whats-new` (whats-new/build.ts) — leave its page alone.
    if (category.slug !== "whats-new") {
      const indexFile = pageFileIn(dir) ?? join(dir, "index.mdx");
      if (used && isReplaceableIndex(indexFile)) {
        writeIfChanged(indexFile, sectionIndexText(category.title, category.description));
      } else if (!used && existsSync(indexFile) && indexInfo(dir).generated && !indexInfo(dir).placeholder) {
        writeIfChanged(indexFile, sectionIndexText(category.title, category.description, { placeholder: true }));
      }
    }
    if (used || isManagedMeta(readJsonObject(join(dir, "meta.json")))) writeMeta(dir, category.title, childrenOf(category.slug));
  }

  // Feature-group sections below a category.
  for (const rel of inUse.keys()) {
    if (!rel.includes("/")) continue;
    const dir = join(contentDir, rel);
    const title = titleOf(rel);
    const indexFile = pageFileIn(dir) ?? join(dir, "index.mdx");
    if (!pageRels.has(rel) && isReplaceableIndex(indexFile)) {
      writeIfChanged(indexFile, sectionIndexText(title, `Step-by-step guides for ${lowerFirstWord(title)}.`));
    }
    if (!pageRels.has(rel)) writeMeta(dir, title, childrenOf(rel));
  }

  writeRootMeta(contentDir);
  writeHome(contentDir, opts.product);
}

/** Post-order: removes section folders the engine generated (`generated: true`, `kind: section`)
 * that no longer hold any page — never a top-level category, a placeholder or a human page. */
function removeEmptyGeneratedSections(contentDir: string, dir: string, inUse: Map<string, string | undefined>): void {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory() && entry.name !== "screenshots" && !entry.name.startsWith(".")) {
      removeEmptyGeneratedSections(contentDir, join(dir, entry.name), inUse);
    }
  }
  if (dir === contentDir) return;
  const rel = toPosix(relative(contentDir, dir));
  if (!rel.includes("/") && CATEGORY_SLUGS.has(rel)) return;
  if (inUse.has(rel) || !existsSync(dir)) return;
  const info = indexInfo(dir);
  if (!info.generated || info.kind !== "section" || info.placeholder) return;
  const remaining = readdirSync(dir).filter((n) => n !== "index.mdx" && n !== "index.mdx.aida.json" && n !== "meta.json");
  if (remaining.length > 0) return;
  const meta = readJsonObject(join(dir, "meta.json"));
  if (meta && meta.generated !== true) return; // a person's meta.json — keep the folder
  rmSync(dir, { recursive: true, force: true });
}

function writeRootMeta(contentDir: string): void {
  const file = join(contentDir, "meta.json");
  const existing = readJsonObject(file);
  if (existsSync(file) && !existing) return;
  const current = Array.isArray(existing?.pages) ? (existing?.pages as unknown[]).filter((p): p is string => typeof p === "string") : [];
  const extras = current.filter((p) => p !== "..." && !ROOT_ORDER.includes(p));
  const meta = { ...(existing ?? {}), title: typeof existing?.title === "string" ? existing.title : "Help", pages: [...ROOT_ORDER, ...extras, "..."] };
  writeIfChanged(file, `${JSON.stringify(meta, null, 2)}\n`);
}

function writeHome(contentDir: string, product: string | undefined): void {
  const file = pageFileIn(contentDir) ?? join(contentDir, "index.mdx");
  if (!isReplaceableIndex(file)) return;
  const name = product?.trim();
  const title = name ? `${name} help` : "Help";
  const description = name ? `Guides, videos and printable instructions for ${name}.` : "Guides, videos and printable instructions.";
  const body =
    "Find the task you want to do below, or search for it. Each guide takes you through one task step by step, with a screenshot for every step.";
  writeIfChanged(file, `${frontmatterBlock({ title, description, kind: "home", generated: true })}\n\n${body}\n`);
}

/** The most common `product` across the given walkthroughs, if any set one. */
export function mostCommonProduct(products: (string | undefined)[]): string | undefined {
  const counts = new Map<string, number>();
  for (const p of products) {
    const name = p?.trim();
    if (name) counts.set(name, (counts.get(name) ?? 0) + 1);
  }
  let best: string | undefined;
  let bestCount = 0;
  for (const [name, count] of [...counts].sort((a, b) => a[0].localeCompare(b[0]))) {
    if (count > bestCount) {
      best = name;
      bestCount = count;
    }
  }
  return best;
}

