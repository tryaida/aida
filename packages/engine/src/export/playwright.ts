// One walkthrough as a `@playwright/test` spec (`aida export playwright`). The walkthrough stays
// the source of truth; the spec is regenerated, never edited. Each action becomes the Playwright
// call capture/runner.ts makes for it, on a locator that means what capture/locate.ts means.
// What a spec can't carry (aida's sign-in adapter, data states and their hooks, emails, the
// run id) is written as a `// TODO from walkthrough:` comment where it happens. Deterministic:
// the same walkthrough and config give the same bytes.
import type { Action, Device, Step, Walkthrough } from "../walkthrough/index.js";
import { personaRole, resolveTemplate, resolveTemplatesDeep, withRunValues } from "../walkthrough/index.js";
import { textPattern } from "../walkthrough/text-pattern.js";
import { CONTROL_CHAR, CodeContext, RUN_ID_MARK, commentText, jsString, regex, str } from "./code.js";
import { SELECT_HELPER, TEXT_HELPER, helperCode } from "./helpers.js";
import { locatorCode } from "./locator.js";

/** First words of every generated spec: how the overwrite guard knows a file is ours. */
export const GENERATED_HEADER = "// Generated by `aida export playwright`";

/** Capture's waits (capture/runner.ts), so a spec gives a slow demo app the same time. */
const EXPECT_MS = "20_000";
const WAIT_MS = "60_000";

export interface SpecContext {
  /** The walkthrough file, relative to the config's directory, with `/` separators. */
  source: string;
  /** The config has a sign-in adapter. */
  signIn: boolean;
  /** Data states the config has a setup hook for. */
  stateSetups: ReadonlySet<string>;
  /** For each data state, the walkthroughs that leave it, sorted. */
  providers: Readonly<Record<string, string[]>>;
  /** The device whose steps are exported: the walkthrough's primary (devices/index.ts). */
  device: Device;
  /** The config's database adapter can reset the demo data. */
  databaseReset: boolean;
}

export function isGeneratedSpec(text: string): boolean {
  return text.startsWith(GENERATED_HEADER);
}

const todo = (text: string): string => `// TODO from walkthrough: ${commentText(text)}`;

function quoteList(items: string[]): string {
  return items.map((i) => `"${i}"`).join(", ");
}

function stateHow(state: string, ctx: SpecContext): string {
  const how: string[] = [];
  const providers = ctx.providers[state] ?? [];
  if (providers.length > 0) how.push(`left by ${quoteList(providers)}, which aida runs first`);
  if (ctx.stateSetups.has(state)) how.push(`made by the config's setup hook for "${state}"`);
  return how.length > 0 ? how.join("; or ") : "nothing in this project leaves it";
}

/** A path for a `storageState` placeholder: the role as a file name, nothing else. */
function sessionFile(role: string | undefined): string {
  const name = (role ?? "default").replace(/[^A-Za-z0-9_-]+/g, "-").replace(/^-+|-+$/g, "") || "default";
  return `playwright/.auth/${name}.json`;
}

/** Origin and path only: a start.baseUrl never brings credentials or a query into the spec. */
function safeUrl(url: string): string {
  try {
    const u = new URL(url);
    return `${u.origin}${u.pathname === "/" ? "" : u.pathname}`;
  } catch {
    return "(not a URL)";
  }
}

class Emitter {
  readonly lines: string[] = [];
  constructor(readonly code: CodeContext) {}

  line(indent: number, text: string): void {
    this.lines.push(text === "" ? "" : `${"  ".repeat(indent)}${text}`);
  }
}

/** A `goto` path Playwright opens against use.baseURL the way capture opens it against the
 * current page: one from the site root, or a whole URL. */
function rootedPath(path: string): boolean {
  return path.startsWith("/") || /^[a-z][a-z0-9+.-]*:/i.test(path);
}

function expectCall(e: Emitter, subject: string, matcher: string, arg: string, timeout: string): string {
  e.code.usesExpect = true;
  return `await expect(${subject}).${matcher}(${arg}${arg ? ", " : ""}{ timeout: ${timeout} });`;
}

/** One action as the Playwright calls capture makes for it (capture/runner.ts `runAction`). */
function emitAction(e: Emitter, a: Action, indent: number): void {
  const c = e.code;
  const loc = (t: Parameters<typeof locatorCode>[0]) => locatorCode(t, "page", c);
  switch (a.do) {
    case "goto":
      // Capture resolves a path against the page it is on ("edit", "?tab=2"); Playwright would
      // resolve it against use.baseURL.
      e.line(indent, rootedPath(a.path) ? `await page.goto(${str(a.path, c)});` : `await page.goto(new URL(${str(a.path, c)}, page.url()).href);`);
      return;
    case "click":
      e.line(indent, `await ${loc(a.target)}.click();`);
      return;
    case "type":
      // Capture types into the field (replacing what's there) and checks it holds the text.
      e.line(indent, `await ${loc(a.target)}.fill(${str(a.text, c)});`);
      return;
    case "select":
      c.helpers.add("select");
      e.line(indent, `await ${SELECT_HELPER}(page, ${loc(a.target)}, ${str(a.option, c)});`);
      return;
    case "point":
      // Pointing only draws the guide's pointer: in a test, the thing pointed at is on screen.
      e.line(indent, expectCall(e, loc(a.target), "toBeVisible", "", EXPECT_MS));
      return;
    case "expect": {
      if (a.text === undefined) {
        e.line(indent, expectCall(e, loc(a.target), "toBeVisible", "", EXPECT_MS));
        return;
      }
      const exact = a.exact ?? false;
      const pattern = textPattern(a.text);
      if (pattern) {
        // Capture tests a pattern against the text with whitespace collapsed; Playwright's text
        // matchers only collapse it for a string, so the spec polls the collapsed text instead.
        c.usesExpect = true;
        c.helpers.add("text");
        const re = regex(exact ? `^(?:${pattern.source})$` : pattern.source, pattern.flags, c);
        e.line(indent, `await expect.poll(() => ${TEXT_HELPER}(${loc(a.target)}), { timeout: ${EXPECT_MS} }).toMatch(${re});`);
        return;
      }
      e.line(indent, expectCall(e, loc(a.target), exact ? "toHaveText" : "toContainText", str(a.text, c), EXPECT_MS));
      return;
    }
    case "press":
      e.line(indent, a.target ? `await ${loc(a.target)}.press(${str(a.key, c)});` : `await page.keyboard.press(${str(a.key, c)});`);
      return;
    case "hover":
      e.line(indent, `await ${loc(a.target)}.hover();`);
      return;
    case "focus":
      e.line(indent, `await ${loc(a.target)}.focus();`);
      return;
    case "waitFor":
      e.line(indent, expectCall(e, loc(a.target), "toBeVisible", "", WAIT_MS));
      return;
    case "waitForUrl":
      e.line(indent, expectCall(e, "page", "toHaveURL", regex(a.pattern, "", c), WAIT_MS));
      return;
    case "scrollTo":
      e.line(indent, `await ${loc(a.target)}.scrollIntoViewIfNeeded();`);
      return;
    case "showEmail": {
      if (a.mock) {
        e.line(indent, todo(`aida shows an example email here ("${a.mock.subject}"), drawn over the app for the guide; there is nothing to check.`));
        return;
      }
      const which = [a.to !== undefined ? `to ${a.to}` : "", a.subject !== undefined ? `with subject ${a.subject}` : ""].filter(Boolean).join(" ");
      e.line(indent, todo(`aida shows the email the app sent ${which}, caught by its local mail catcher. Check it with your own mail catcher.`));
      const keys = Object.keys(a.remember ?? {}).sort();
      if (keys.length > 0) {
        for (const k of keys) e.code.inboxKeys.add(k);
        e.line(indent, todo(`aida reads ${keys.map((k) => `{{inbox.${k}}}`).join(", ")} from that email; set ${keys.map((k) => `inbox["${k}"]`).join(", ")} from it here.`));
      }
      return;
    }
    default: {
      const unknown: never = a;
      throw new Error(`unknown action ${(unknown as Action).do}`);
    }
  }
}

function stepTitle(step: Step, index: number): string {
  return step.title ?? step.id ?? `Step ${index + 1}`;
}

/** A title as a string literal, `{{data}}` filled in where it can be: a title is only a label,
 * so `{{run.id}}` and `{{inbox.*}}` stay as written. */
function titleCode(text: string, data: Record<string, unknown>): string {
  let label = text;
  try {
    label = resolveTemplate(text, data);
  } catch {
    // left as written
  }
  return jsString(label.split(RUN_ID_MARK).join("{{run.id}}"));
}

/** The spec text for one walkthrough. Throws on a `{{placeholder}}` its data doesn't have, as a
 * capture of it would. */
export function walkthroughToSpec(wt: Walkthrough, ctx: SpecContext): string {
  // A line break in the file name would end the header comment and start code.
  if (CONTROL_CHAR.test(ctx.source)) {
    throw new Error(`the file name ${JSON.stringify(ctx.source)} has a control character (a line break, a tab): rename the file to export it`);
  }
  const code = new CodeContext();
  const data = withRunValues(wt.data, { id: RUN_ID_MARK });
  const e = new Emitter(code);

  // The steps first: what they use decides what the test declares above them.
  wt.steps.forEach((step, index) => {
    const title = titleCode(stepTitle(step, index), data);
    if (step.devices && !step.devices.includes(ctx.device)) {
      e.line(1, `// Step ${commentText(title)} only runs on ${step.devices.join(", ")}: not in this ${ctx.device} spec.`);
      return;
    }
    const actions: Action[] = resolveTemplatesDeep(step.actions, data);
    e.line(1, `await test.step(${title}, async () => {`);
    if (actions.length === 0) e.line(2, "// Nothing to do in this step: the guide only explains it.");
    for (const a of actions) emitAction(e, a, 2);
    e.line(1, "});");
  });

  const before: string[] = [];
  const role = personaRole(wt.start);
  if (ctx.databaseReset) before.push(todo("aida resets the demo data (the config's database adapter) before a run that starts with this walkthrough. Start this test from the same data."));
  for (const state of wt.needs ?? []) {
    before.push(todo(`needs data state "${state}" before step 1: ${stateHow(state, ctx)}. Make sure this test starts with that data.`));
  }
  if (wt.setup && wt.setup.steps.length > 0) {
    const titles = wt.setup.steps.map((s, i) => titleCode(stepTitle(s, i), data));
    const as = wt.setup.as && wt.setup.as !== role ? ` signed in as "${wt.setup.as}"` : "";
    before.push(todo(`before step 1 aida runs ${wt.setup.steps.length} unrecorded setup step(s)${as}: ${titles.join(", ")}. Do the same in a beforeEach or a fixture.`));
  }
  if (code.usesRunId) {
    before.push(todo("{{run.id}} is a short id aida makes once per run, shared by every walkthrough in it so one can find what another made. Use the id your test data was made with."));
    before.push('const runId = process.env.AIDA_RUN_ID ?? "local";');
  }
  if (code.inboxKeys.size > 0) {
    before.push(todo(`values aida reads from emails during the run (${[...code.inboxKeys].sort().map((k) => `{{inbox.${k}}}`).join(", ")}): fill them in where the email is shown.`));
    before.push("const inbox: Record<string, string> = {};");
  }
  if (wt.start?.baseUrl) before.push(todo(`the walkthrough starts at ${safeUrl(wt.start.baseUrl)}: set use.baseURL to it.`));
  before.push(`await page.goto(${str(wt.start?.page ?? "/", code)});`);

  const after: string[] = [];
  const checks = (wt.validate?.database ?? []).map((d) => d.name);
  if (checks.length > 0) after.push(todo(`after the last step aida checks the database (validate.database): ${quoteList(checks)}.`));
  if ((wt.leaves ?? []).length > 0) after.push(todo(`leaves data state(s) ${quoteList(wt.leaves!)} for the walkthroughs that need them.`));
  if ((wt.clears ?? []).length > 0) after.push(todo(`clears data state(s) ${quoteList(wt.clears!)}.`));
  if ((wt.paths ?? []).length > 0) {
    after.push(todo(`other ways in, captured by aida but not exported: ${wt.paths!.map((p) => `"${p.id}" (${p.title})`).join(", ")}.`));
  }

  const out: string[] = [
    `${GENERATED_HEADER} from ${commentText(ctx.source)} (walkthrough "${commentText(wt.walkthrough)}").`,
    "// The walkthrough is the source of truth: change it and run `aida export playwright` again. Don't edit this file.",
    "// Locators find what aida's capture finds: visible elements only, the first match unless the walkthrough picks another.",
    "// Paths open against use.baseURL in your playwright.config.",
  ];
  if (ctx.device !== "desktop") out.push(commentText(`// These are the ${ctx.device} steps: run this spec with a ${ctx.device} viewport.`));
  const helpers = helperCode(code);
  const types = [...(helpers.length > 0 ? ["type Locator"] : []), ...(code.helpers.has("label") || code.helpers.has("select") ? ["type Page"] : [])].map((t) => `, ${t}`).join("");
  out.push(`import { ${code.usesExpect ? "expect, " : ""}test${types} } from "@playwright/test";`, "", ...helpers);
  if (ctx.signIn) {
    out.push(
      todo(`aida signs in${role ? ` as "${role}"` : ""} with the config's sign-in adapter. Save a signed-in session for ${role ? "that role" : "it"} (https://playwright.dev/docs/auth) at this path.`),
      `test.use({ storageState: ${jsString(sessionFile(role))} });`,
      "",
    );
  }
  out.push(`test(${titleCode(wt.title, data)}, async ({ page }) => {`);
  for (const l of before) out.push(`  ${l}`);
  out.push(...e.lines);
  for (const l of after) out.push(`  ${l}`);
  out.push("});", "");
  return out.join("\n");
}
