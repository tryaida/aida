// Builds the help app's client-side search index (scope.md "Swappable
// providers" / M7 scope item 6): walks a Fumadocs `content/` directory, pulls
// each page's frontmatter + headings, and writes one flat JSON file read by
// help-app/components/search-box.tsx — no server, no database, works on a
// fully static export. `aida build` calls this after the page builder
// (packages/engine/src/pages) has written content/.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, sep } from "node:path";
import { parse as parseYaml } from "yaml";
import type { BuildSearchIndexResult, SearchIndexEntry } from "./types.js";

const MARKDOWN_EXTENSIONS = new Set([".md", ".mdx"]);
// Matches both the legacy HTML-comment marker (`<!-- aida:begin key -->`) and the current
// MDX-comment form (`{/* aida:begin key */}`) — see pages/markers.ts. Previously only the
// HTML form was stripped, so an MDX page's markers leaked into search snippets verbatim.
const AIDA_MARKER = /<!--\s*aida:(?:begin|end)[^>]*-->|\{\/\*\s*aida:(?:begin|end)[^*]*\*\/\}/g;
const SNIPPET_LENGTH = 300;

function findContentFiles(dir: string): string[] {
  const out: string[] = [];
  const walk = (current: string) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const full = join(current, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (MARKDOWN_EXTENSIONS.has(extname(entry.name)) && !entry.name.endsWith(".plain.md")) {
        out.push(full);
      }
    }
  };
  walk(dir);
  return out.sort();
}

function parseFrontmatter(raw: string): { data: Record<string, unknown>; body: string } {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { data: {}, body: raw };
  const data = (parseYaml(match[1]) as Record<string, unknown>) ?? {};
  return { data, body: raw.slice(match[0].length) };
}

/** `content/docs/how-do-i/add-competitor/index.md` -> `/how-do-i/add-competitor`; `content/docs/index.mdx` -> `/`. */
function urlFor(contentDir: string, file: string): string {
  const rel = relative(contentDir, file).split(sep).join("/");
  const withoutExt = rel.replace(/\.(mdx?|md)$/, "");
  const withoutIndex = withoutExt.replace(/(^|\/)index$/, "");
  return withoutIndex === "" ? "/" : `/${withoutIndex}`;
}

/** Exported for reuse by procedures/build.ts (walkthrough `page_text` -> plain instruction).
 * Drops everything a reader never sees as text — MDX comments (`{/* ... *\/}`, including
 * aida's generated-block markers and its "Generated by aida" header), HTML comments, JSX/HTML
 * tags, images — and Markdown syntax, leaving plain words for search snippets. */
export function stripMarkdown(text: string): string {
  return text
    .replace(AIDA_MARKER, "")
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, "") // MDX comments
    .replace(/<!--[\s\S]*?-->/g, "") // HTML comments
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "") // images
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1") // links -> link text
    .replace(/<\/?[A-Za-z][\w.:-]*(?:\s[^<>]*)?\/?>/g, " ") // JSX/HTML tags (inner text kept)
    .replace(/^#{1,6}\s*/gm, "")
    .replace(/^\s*[-*+]\s+/gm, "") // list bullets
    .replace(/\\([\\{}<>])/g, "$1") // MDX escapes (pages/content.ts escapeMdxText)
    .replace(/[*_`>]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Heading ids the way the help site renders them: Fumadocs' remark-heading uses github-slugger
 * — lowercase, drop punctuation and symbols (keeping letters, numbers, `-` and `_`), each space
 * becomes `-`, and a repeat within one page gets `-1`, `-2`, ... A heading hit's URL anchor then
 * lands on the right heading.
 */
export class HeadingSlugger {
  private seen = new Map<string, number>();

  slug(text: string): string {
    const base = text.toLowerCase().replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, "").replace(/ /g, "-");
    let result = base;
    while (this.seen.has(result)) {
      const n = (this.seen.get(base) ?? 0) + 1;
      this.seen.set(base, n);
      result = `${base}-${n}`;
    }
    this.seen.set(result, 0);
    return result;
  }
}

/** Splits a page body into a lead section (before the first heading) and one section per `##`/`###`
 * heading, each heading with the id the site gives it (every heading level counts toward
 * github-slugger's repeat numbering, as on the rendered page). */
function sectionsOf(body: string): { heading?: string; anchor?: string; text: string }[] {
  // MDX comments can span lines; drop them before splitting so a comment line is never mistaken
  // for text (or a heading).
  const lines = body.replace(/\{\/\*[\s\S]*?\*\/\}/g, "").split("\n");
  const slugger = new HeadingSlugger();
  const sections: { heading?: string; anchor?: string; text: string }[] = [];
  let current: { heading?: string; anchor?: string; text: string } = { text: "" };
  let inFence = false;

  for (const line of lines) {
    if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
    const headingMatch = inFence ? null : line.match(/^(#{1,6})\s+(.*?)\s*#*\s*$/);
    if (headingMatch) {
      const heading = stripMarkdown(headingMatch[2]);
      const anchor = slugger.slug(heading);
      if (headingMatch[1].length === 2 || headingMatch[1].length === 3) {
        if (current.text.trim() || current.heading) sections.push(current);
        current = { heading, anchor, text: "" };
        continue;
      }
      if (headingMatch[1].length === 1) continue; // the page title — already the entry's `title`
    }
    current.text += `${line}\n`;
  }
  if (current.text.trim() || current.heading) sections.push(current);

  return sections
    .map((s) => ({ heading: s.heading, anchor: s.anchor, text: stripMarkdown(s.text).slice(0, SNIPPET_LENGTH) }))
    .filter((s) => s.text.length > 0 || s.heading);
}

/**
 * Walks `contentDir` (a Fumadocs `content/docs`-style tree) and builds a flat search index: one
 * entry per page lead paragraph plus one per heading. Pages whose frontmatter sets `passed: false`
 * are skipped, matching the page builder's publish filter. Pass `outFile` to also write the result
 * as JSON (the shape `help-app`'s search box fetches).
 */
export function buildSearchIndex(contentDir: string, outFile?: string): BuildSearchIndexResult {
  const files = existsSync(contentDir) ? findContentFiles(contentDir) : [];
  const entries: SearchIndexEntry[] = [];
  let pageCount = 0;

  for (const file of files) {
    const raw = readFileSync(file, "utf8");
    const { data, body } = parseFrontmatter(raw);
    if (data.passed === false) continue;
    // Template placeholders are hidden on the site until real pages replace them.
    if (data.placeholder === true) continue;

    const title = typeof data.title === "string" ? data.title : relative(contentDir, file);
    const url = urlFor(contentDir, file);
    const section = typeof data.section === "string" && data.section ? data.section : undefined;
    pageCount += 1;

    const sections = sectionsOf(body);
    if (sections.length === 0) {
      // A section/category page has no body (the site lists its pages as cards) — still make it
      // findable by its title and description.
      const description = typeof data.description === "string" ? data.description : "";
      entries.push({ url, title, text: stripMarkdown(description).slice(0, SNIPPET_LENGTH), ...(section ? { section } : {}) });
      continue;
    }
    for (const s of sections) {
      entries.push({
        url: s.heading && s.anchor ? `${url}#${s.anchor}` : url,
        title,
        heading: s.heading,
        text: s.text,
        ...(section ? { section } : {}),
      });
    }
  }

  const result: BuildSearchIndexResult = { entries, pageCount };

  if (outFile) {
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, JSON.stringify(entries, null, 2), "utf8");
    result.outFile = outFile;
  }

  return result;
}
